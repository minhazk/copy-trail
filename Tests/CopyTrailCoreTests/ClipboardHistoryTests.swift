import XCTest
@testable import CopyTrailCore

@MainActor
private final class FakeClipboard: ClipboardAccess {
    var changeCount = 0
    var typeNames: Set<String> = []
    var text: String?
    var readCount = 0
    var writeCount = 0
    var writeSucceeds = true
    var changesDuringRead = false

    func copy(_ value: String, types: Set<String> = []) {
        text = value
        typeNames = types
        changeCount += 1
    }

    func readText() -> String? {
        readCount += 1
        if changesDuringRead { changeCount += 1 }
        return text
    }

    func writeText(_ value: String) -> Bool {
        writeCount += 1
        guard writeSucceeds else { return false }
        copy(value)
        return true
    }
}

final class ClipboardHistoryTests: XCTestCase {
    @MainActor func testStartupDoesNotReadExistingClipboard() async {
        let board = FakeClipboard()
        board.copy("Before launch")
        let history = ClipboardHistory(clipboard: board)
        history.poll()
        XCTAssertEqual(board.readCount, 0)
        XCTAssertTrue(history.clips.isEmpty)
    }

    @MainActor func testPollingRecordsOnlyChangesWithoutWriting() async {
        let board = FakeClipboard()
        let history = ClipboardHistory(clipboard: board)
        board.copy("https://example.com")
        history.poll()
        history.poll()
        XCTAssertEqual(history.clips.map(\.text), ["https://example.com"])
        XCTAssertEqual(board.readCount, 1)
        XCTAssertEqual(board.writeCount, 0)
    }

    @MainActor func testDuplicatesMoveToFrontAndKeepIdentity() async {
        let board = FakeClipboard()
        let history = ClipboardHistory(clipboard: board, capacity: 2)
        board.copy("one"); history.poll()
        let id = history.clips[0].id
        board.copy("two"); history.poll()
        board.copy("one"); history.poll()
        XCTAssertEqual(history.clips.map(\.text), ["one", "two"])
        XCTAssertEqual(history.clips[0].id, id)
        board.copy("three"); history.poll()
        XCTAssertEqual(history.clips.map(\.text), ["three", "one"])
    }

    @MainActor func testSensitiveAndRemoteTypesAreNotRead() async {
        let board = FakeClipboard()
        let history = ClipboardHistory(clipboard: board)
        for type in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                     "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
                     "com.apple.is-remote-clipboard"] {
            board.copy("ignored", types: [type])
            history.poll()
        }
        XCTAssertEqual(board.readCount, 0)
        XCTAssertTrue(history.clips.isEmpty)
    }

    @MainActor func testPausedCopiesAreNeverBackfilled() async {
        let board = FakeClipboard()
        let history = ClipboardHistory(clipboard: board)
        history.setPaused(true)
        board.copy("paused"); history.poll()
        board.copy("also paused")
        history.setPaused(false)
        history.poll()
        XCTAssertEqual(board.readCount, 0)
        board.copy("resumed"); history.poll()
        XCTAssertEqual(history.clips.map(\.text), ["resumed"])
    }

    @MainActor func testClearAndDeleteDoNotChangeClipboard() async {
        let board = FakeClipboard()
        let history = ClipboardHistory(clipboard: board)
        board.copy("keep active"); history.poll()
        history.remove(history.clips[0].id)
        XCTAssertTrue(history.clips.isEmpty)
        board.copy("still active"); history.poll()
        history.clear()
        history.poll()
        XCTAssertTrue(history.clips.isEmpty)
        XCTAssertEqual(board.text, "still active")
        XCTAssertEqual(board.writeCount, 0)
    }

    @MainActor func testRestoreWritesOnceAndDoesNotRecapture() async {
        let board = FakeClipboard()
        let history = ClipboardHistory(clipboard: board)
        board.copy("old"); history.poll()
        let old = history.clips[0]
        board.copy("new"); history.poll()
        XCTAssertTrue(history.restore(old))
        history.poll()
        XCTAssertEqual(board.text, "old")
        XCTAssertEqual(board.writeCount, 1)
        XCTAssertEqual(board.readCount, 2)
        XCTAssertEqual(history.clips.map(\.text), ["old", "new"])
    }

    @MainActor func testFailedRestoreReportsError() async {
        let board = FakeClipboard()
        let history = ClipboardHistory(clipboard: board)
        board.copy("example"); history.poll()
        board.writeSucceeds = false
        XCTAssertFalse(history.restore(history.clips[0]))
        XCTAssertNotNil(history.message)
    }

    @MainActor func testBlankOversizeAndRacingReadsAreIgnored() async {
        let board = FakeClipboard()
        let history = ClipboardHistory(clipboard: board)
        board.copy(" \n\t"); history.poll()
        board.copy(String(repeating: "a", count: 1_000_001)); history.poll()
        board.changesDuringRead = true
        board.copy("unstable"); history.poll()
        XCTAssertTrue(history.clips.isEmpty)
    }

    @MainActor func testSearchPreservesOriginalText() async {
        let board = FakeClipboard()
        let history = ClipboardHistory(clipboard: board)
        board.copy("  Café LINK\n"); history.poll()
        board.copy("something else"); history.poll()
        XCTAssertEqual(history.matching("cafe").map(\.text), ["  Café LINK\n"])
        XCTAssertEqual(history.matching("link").count, 1)
        XCTAssertEqual(history.matching("").count, 2)
        XCTAssertTrue(history.matching("missing").isEmpty)
    }
}
